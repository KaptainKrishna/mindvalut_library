const { Schema, model } = require("mongoose");

const contactSchema = new Schema(
  {
    fullname: {
      type: String,
      required: true,
    },
    email: {
      type: String,
      required: true,
    },
    mobile: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
  },
  { timestamps: true },
);

const ContactModel = model("Contact", contactSchema);
module.exports = ContactModel;
